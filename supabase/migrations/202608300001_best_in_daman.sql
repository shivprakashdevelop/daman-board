create table if not exists public.listings (
  id uuid primary key default gen_random_uuid(),
  owner_id uuid references auth.users(id) on delete set null,
  listing_name text not null,
  category text not null check (category in ('Food & drink', 'Things to do', 'Services', 'Community', 'Wellness', 'Shopping & stays')),
  description text not null,
  destination_url text not null,
  preferred_cta text not null default 'Visit website' check (preferred_cta in ('Call', 'WhatsApp', 'Directions', 'Instagram', 'Visit website')),
  owner_name text not null,
  contact_value text not null,
  status text not null default 'pending' check (status in ('pending', 'approved', 'rejected', 'paused', 'deleted')),
  moderation_reason text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.campaigns (
  id uuid primary key default gen_random_uuid(),
  listing_id uuid not null references public.listings(id) on delete cascade,
  package_id text not null references public.campaign_packages(id),
  status text not null default 'pending' check (status in ('pending', 'approved', 'active', 'paused', 'rejected', 'completed', 'cancelled')),
  requested_start_at timestamptz not null,
  start_at timestamptz,
  end_at timestamptz,
  total_price_inr integer not null check (total_price_inr > 0),
  rejection_reason text,
  cancellation_notes text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.listing_events (
  id bigint generated by default as identity primary key,
  listing_id uuid not null references public.listings(id) on delete cascade,
  campaign_id uuid not null references public.campaigns(id) on delete cascade,
  event_type text not null check (event_type in ('homepage_impression', 'listing_impression', 'listing_view', 'unique_viewer', 'website_tap', 'whatsapp_tap', 'call_tap', 'directions_tap', 'instagram_visit', 'save', 'share')),
  viewer_hash text,
  occurred_at timestamptz not null default now()
);

create table if not exists public.analytics_counters (
  listing_id uuid not null references public.listings(id) on delete cascade,
  campaign_id uuid not null references public.campaigns(id) on delete cascade,
  event_type text not null,
  event_count bigint not null default 0 check (event_count >= 0),
  unique_count bigint not null default 0 check (unique_count >= 0),
  updated_at timestamptz not null default now(),
  primary key (campaign_id, event_type)
);

create table if not exists public.admin_profiles (
  user_id uuid primary key references auth.users(id) on delete cascade,
  role text not null default 'moderator' check (role in ('moderator', 'admin')),
  created_at timestamptz not null default now()
);

create table if not exists public.payment_records (
  id uuid primary key default gen_random_uuid(),
  campaign_id uuid not null references public.campaigns(id) on delete cascade,
  provider text not null default 'manual',
  status text not null default 'pending' check (status in ('pending', 'paid', 'failed', 'refunded', 'cancelled')),
  amount_inr integer not null check (amount_inr > 0),
  provider_reference text,
  admin_notes text,
  refund_notes text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists idx_listings_public_status on public.listings (status, category);
create index if not exists idx_campaigns_active_dates on public.campaigns (status, start_at, end_at);
create index if not exists idx_campaigns_listing_id on public.campaigns (listing_id);
create index if not exists idx_listing_events_campaign_type on public.listing_events (campaign_id, event_type, occurred_at);
create index if not exists idx_payment_records_campaign_id on public.payment_records (campaign_id);

