create policy "packages are public" on public.campaign_packages for select to anon, authenticated using (true);

create policy "public can read approved active listings" on public.listings for select to anon, authenticated using (
  status = 'approved' and exists (
    select 1 from public.campaigns c
    where c.listing_id = listings.id and c.status = 'active'
      and c.start_at <= now() and c.end_at > now()
  )
);
create policy "public can submit pending listings" on public.listings for insert to anon, authenticated with check (status = 'pending');
create policy "owners can read their listings" on public.listings for select to authenticated using (owner_id = auth.uid());
create policy "admins manage listings" on public.listings for all to authenticated using (exists (select 1 from public.admin_profiles a where a.user_id = auth.uid())) with check (exists (select 1 from public.admin_profiles a where a.user_id = auth.uid()));

create policy "public can read active campaigns" on public.campaigns for select to anon, authenticated using (
  status = 'active' and start_at <= now() and end_at > now()
);
create policy "public can submit pending campaigns" on public.campaigns for insert to anon, authenticated with check (status = 'pending');
create policy "owners can read their campaigns" on public.campaigns for select to authenticated using (exists (select 1 from public.listings l where l.id = listing_id and l.owner_id = auth.uid()));
create policy "admins manage campaigns" on public.campaigns for all to authenticated using (exists (select 1 from public.admin_profiles a where a.user_id = auth.uid())) with check (exists (select 1 from public.admin_profiles a where a.user_id = auth.uid()));

create policy "public may record approved campaign events" on public.listing_events for insert to anon, authenticated with check (
  exists (select 1 from public.campaigns c where c.id = campaign_id and c.listing_id = listing_events.listing_id and c.status = 'active' and c.start_at <= now() and c.end_at > now())
);
create policy "admins read listing events" on public.listing_events for select to authenticated using (exists (select 1 from public.admin_profiles a where a.user_id = auth.uid()));

create policy "owners read their counters" on public.analytics_counters for select to authenticated using (exists (select 1 from public.listings l where l.id = listing_id and l.owner_id = auth.uid()));
create policy "admins manage counters" on public.analytics_counters for all to authenticated using (exists (select 1 from public.admin_profiles a where a.user_id = auth.uid())) with check (exists (select 1 from public.admin_profiles a where a.user_id = auth.uid()));

create policy "admins read own profile" on public.admin_profiles for select to authenticated using (user_id = auth.uid());
create policy "owners read their payment records" on public.payment_records for select to authenticated using (exists (select 1 from public.campaigns c join public.listings l on l.id = c.listing_id where c.id = campaign_id and l.owner_id = auth.uid()));
create policy "admins manage payment records" on public.payment_records for all to authenticated using (exists (select 1 from public.admin_profiles a where a.user_id = auth.uid())) with check (exists (select 1 from public.admin_profiles a where a.user_id = auth.uid()));
